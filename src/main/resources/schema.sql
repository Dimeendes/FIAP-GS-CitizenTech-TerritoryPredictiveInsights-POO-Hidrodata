CREATE TABLE IF NOT EXISTS medicao (
    id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_Id INT NOT NULL,
    tipo_sensor VARCHAR(20) NOT NULL,
    valor DOUBLE PRECISION NOT NULL CHECK (valor >= 0),
    data_hora TIMESTAMP NOT NULL
);

CREATE INDEX if NOT EXISTS idx_medicao_sensor_data ON medicao (sensor_Id, data_hora);

CREATE TABLE IF NOT EXISTS alerta(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id INT NOT NULL,
    tipo_sensor VARCHAR(20) NOT NULL,
    nivel VARCHAR(10) NOT NULL CHECK (nivel IN ('BAIXO', 'MÉDIO', 'ALTO')),
    valor_previsto DOUBLE PRECISION NOT NULL,
    limite DOUBLE PRECISION NOT NULL,
    estrategia VARCHAR(40) NOT NULL,
    mensagem VARCHAR(500) NOT NULL,
    data_hora TIMESTAMP NOT NULL
)